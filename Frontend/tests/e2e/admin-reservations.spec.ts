import { expect, test } from '@playwright/test'
test('administrador ve reservas de todos los usuarios sin acciones de creación', async ({ page }) => {
  const responsePromise = page.waitForResponse(r => r.url().includes('/api/v1/admin/reservas'))
  await page.goto('/#/administracion/reservas')
  expect((await responsePromise).status()).toBe(200)
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(6)
  await expect(page.locator('.desktop-table')).toContainText('user-002')
  await expect(page.locator('.desktop-table')).toContainText('user-003')
  await expect(page.getByRole('button', { name: 'Nueva reserva', exact: true })).toHaveCount(0)
  await expect(page.getByText('Escenarios de demostración', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Ver detalle de 00000000-0000-4000-8000-200000000005', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('user-002')
  await expect(page.getByRole('button', { name: 'Modificar reserva', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Cancelar reserva', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await page.getByRole('combobox', { name: 'Recurso', exact: true }).selectOption('00000000-0000-4000-8000-100000000003')
  await expect(page.getByRole('heading', { name: 'No encontramos coincidencias' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Crear.*reserva/ })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Recurso', exact: true }).selectOption('')
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(6)
  await page.screenshot({ path: 'test-results/admin-reservas.png', fullPage: true, animations: 'disabled' })
})
test('reservas administrativas se adaptan a móvil y usuario conserva acceso personal', async ({ page, request }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/administracion/reservas')
  await expect(page.locator('.mobile-cards .reservation-card')).toHaveCount(6)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/admin-reservas-mobile.png', fullPage: true, animations: 'disabled' })
  const forbidden = await request.get('/api/v1/admin/reservas', { headers: { Authorization: 'Bearer demo-user' } })
  expect(forbidden.status()).toBe(403)
  await page.goto('/#/reservas')
  await expect(page.locator('.mobile-cards .reservation-card')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'Nueva reserva', exact: true })).toBeVisible()
  await expect(page.getByText('Escenarios de demostración', { exact: true })).toHaveCount(0)
})
