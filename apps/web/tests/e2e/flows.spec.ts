test('paginación real y recuperación de error de lectura', async ({ page }) => {
  await page.goto('/#/reservas')
  await scenario(page, 'paginated', true)
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(2)
  await page.getByRole('button', { name: 'Cargar más' }).click()
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(4)
  await expect(page.getByRole('button', { name: 'Cargar más' })).toHaveCount(0)
  await scenario(page, 'error', true)
  await expect(page.getByRole('button', { name: 'Reintentar' })).toBeVisible()
  await scenario(page, 'normal', true)
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(4)
})
test('crea reserva con horario válido, muestra conflicto y permite corregir', async ({ page }) => {
  await page.goto('/#/reservas/nueva')
  await page.getByRole('button', { name: /Recurso 1/ }).click()
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await expect(page.locator('.availability-head').getByText('Horarios disponibles', { exact: true })).toBeVisible()
  await expect(page.locator('input[type="time"]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '19:00 – 20:00', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Continuar', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '18:00 – 19:00', exact: true }).click()
  await page.screenshot({ path: 'test-results/horarios-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await scenario(page, 'conflict')
  await page.getByRole('button', { name: 'Confirmar reserva', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('no está disponible')
  await expect(page.locator('.review-card')).toContainText('18:00 – 19:00')
  await scenario(page, 'success')
  await page.getByRole('button', { name: 'Confirmar reserva', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Reserva confirmada', exact: true })).toBeVisible()
  await expect(page.getByText('Esta respuesta es prefijada', { exact: false })).toBeVisible()
})
