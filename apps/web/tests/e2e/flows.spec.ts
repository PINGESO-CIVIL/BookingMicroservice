import { expect, test, type Page } from '@playwright/test'
async function scenario(page: Page, value: string, read = false) {
  await page.route('**/api/v1/**', route => { const method = route.request().method(); const applies = read ? method === 'GET' : method !== 'GET'; return route.continue({ headers: { ...route.request().headers(), ...(applies ? { 'x-mock-scenario': value } : {}) } }) });
  if (read) await page.reload();
}
test('cada reserva abre su detalle y los estados limitan acciones', async ({ page }) => {
  await page.goto('/#/reservas')
  await expect(page.locator('.desktop-table tbody tr')).toHaveCount(4)
  const expiredReservation = '00000000-0000-4000-8000-200000000003'
  const link = page.locator(`.desktop-table a[href="#/reservas/${expiredReservation}"]`)
  await expect(page.locator('.desktop-table')).not.toContainText(expiredReservation)
  await expect(link).toHaveAccessibleName(/Ver detalle de Recurso 1/)
  await link.click()
  await expect(page).toHaveURL(new RegExp(`${expiredReservation}$`))
  await expect(page.getByRole('heading', { name: 'Detalle de reserva' })).toBeVisible()
  await expect(page.locator('.detail-card')).not.toContainText(expiredReservation)
  await expect(page.getByText('El plazo para cancelar o reprogramar esta reserva venció.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Cancelar reserva', exact: true })).toHaveCount(0)
  await page.goto('/#/reservas/00000000-0000-4000-8000-200000000002')
  await expect(page.locator('.badge')).toContainText('Cancelada')
  await page.goto('/#/reservas/00000000-0000-4000-8000-200000000999')
  await expect(page.getByRole('alert')).toContainText('Reserva no encontrada')
})
